  static List<String> getRegioes() {
    final regioes = municipios.values
        .map((v) => v['regiao'] as String)
        .toSet()
        .toList();
    regioes.sort();
    return regioes;
  }

  static List<String> getMunicipiosPorRegiao(String regiao) {
    final lista = municipios.entries
        .where((e) => e.value['regiao'] == regiao)
        .map((e) => e.key)
        .toList();
    lista.sort();
    return lista;
  }

  static String getSoloPorMunicipio(String municipio) {
    return municipios[municipio]?['solo'] as String? ?? 'Franco';
  }

  static List<String> getMunicipios() {
    final lista = municipios.keys.toList();
    lista.sort();
    return lista;
  }
